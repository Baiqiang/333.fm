/**
 * Optimal HTR length with NISS, sampled per HTR coset, written to utils/htr-niss-data.ts.
 *
 * NISS length depends on the full state, not only the coset, so every coset gets the same
 * number of uniformly random states; bucket distributions are then weighted exactly.
 * Before sampling, the solver is checked against insertionfinder and an unpruned search.
 *
 * Usage (in frontend/): npx jiti scripts/htr-niss.ts [samplesPerCoset]
 */
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

import { Algorithm, Cube } from 'insertionfinder'

import { getHTRCosetTable, readDRPieces } from '../utils/htr-coset'
import { getHTRSubsetStats } from '../utils/htr-subset-stats'

const SAMPLES_PER_COSET = Number(process.argv[2]) || 50
const VERIFY_STATES = 300
const SLICE_EDGES = [1, 3, 5, 7]
const OTHER_EDGES = [0, 2, 4, 6]

function shuffle<T>(list: T[]): T[] {
  const a = [...list]
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]]
  }
  return a
}

function invert(moves: string[]) {
  return [...moves].reverse().map(m => m.endsWith('2') ? m : m.endsWith('\'') ? m[0] : `${m}'`)
}

function permutations(list: number[]): number[][] {
  if (list.length === 0)
    return [[]]
  return list.flatMap((x, i) => permutations(list.filter((_, j) => j !== i)).map(p => [x, ...p]))
}

function verify() {
  const t = getHTRCosetTable()
  const solved = new Cube().toFaceletString()
  const piecesOf = (moves: string) => {
    const cube = new Cube()
    cube.twist(new Algorithm(moves))
    return cube
  }
  const allPremoves = Array.from({ length: t.size }, (_, c) => {
    const pieces = readDRPieces(piecesOf(t.pathTo(c).join(' ')).toFaceletString(), solved)!
    return { d: t.distance[c], ...pieces }
  })
  let improved = 0
  for (let i = 0; i < VERIFY_STATES; i++) {
    const scramble = Array.from({ length: 40 }, () => t.moves[Math.floor(Math.random() * t.moves.length)]).join(' ')
    const pieces = readDRPieces(piecesOf(scramble).toFaceletString(), solved)!
    const niss = t.nissSolve(pieces)
    const cube = piecesOf(`${invert(niss.inverse).join(' ')} ${scramble} ${niss.normal.join(' ')}`)
    if (!cube.isHalfTurnReductionSolved() || niss.normal.length + niss.inverse.length !== niss.length)
      throw new Error(`Invalid NISS solution for ${scramble}`)
    let exhaustive = Infinity
    for (const p of allPremoves) {
      const d = p.d + t.distance[t.cosetOf({ corners: pieces.corners.map(x => p.corners[x]), edges: pieces.edges.map(x => p.edges[x]) })]
      exhaustive = Math.min(exhaustive, d)
    }
    if (exhaustive !== niss.length)
      throw new Error(`Not optimal for ${scramble}: ${niss.length} vs ${exhaustive}`)
    if (niss.length < t.distance[t.cosetOf(pieces)])
      improved++
  }
  console.log(`Verified ${VERIFY_STATES} states (${improved} improved by NISS)`)
}

function main() {
  const t0 = Date.now()
  verify()
  const t = getHTRCosetTable()
  const identity = [0, 1, 2, 3, 4, 5, 6, 7]
  const cornersOfCoset: number[][][] = Array.from({ length: 420 }, () => [])
  for (const perm of permutations(identity))
    cornersOfCoset[t.cornerCoset[t.cosetOf({ corners: perm, edges: identity })]].push(perm)

  const randomState = (coset: number) => {
    const cornerList = cornersOfCoset[t.cornerCoset[coset]]
    const mask = t.edgeMask[coset]
    const slice = shuffle(SLICE_EDGES)
    const other = shuffle(OTHER_EDGES)
    return {
      corners: cornerList[Math.floor(Math.random() * cornerList.length)],
      edges: identity.map(pos => (mask >> pos) & 1 ? slice.pop()! : other.pop()!),
    }
  }

  const data: Record<string, number[][]> = {}
  for (const subset of getHTRSubsetStats().subsets) {
    data[subset.name] = subset.edges.map((edge) => {
      const counts: number[] = []
      for (const coset of edge.cosets) {
        for (let i = 0; i < SAMPLES_PER_COSET; i++) {
          const state = randomState(coset)
          if (t.cosetOf(state) !== coset)
            throw new Error('Sampled state outside its coset')
          const d = t.nissLength(state)
          while (counts.length <= d)
            counts.push(0)
          counts[d]++
        }
      }
      return counts
    })
    const total = data[subset.name].flat().reduce((a, b) => a + b, 0)
    const mean = data[subset.name].flatMap(c => c.map((n, d) => n * d)).reduce((a, b) => a + b, 0) / total
    console.log(`${subset.name.padEnd(8)} normal ${(subset.distances.reduce((s, n, d) => s + n * d, 0) / subset.weight).toFixed(2)}  NISS ${mean.toFixed(3)}  (${Date.now() - t0}ms)`)
  }

  const file = fileURLToPath(new URL('../utils/htr-niss-data.ts', import.meta.url))
  writeFileSync(file, `// Generated by scripts/htr-niss.ts, do not edit.

export const HTR_NISS_SAMPLES_PER_COSET = ${SAMPLES_PER_COSET}

/** Sampled state count per optimal NISS HTR length, by subset and edge bucket. */
export const HTR_NISS_DISTANCES: Record<string, number[][]> = {
${Object.entries(data).map(([name, buckets]) => `  '${name}': [\n${buckets.map(c => `    [${c.join(', ')}],`).join('\n')}\n  ],`).join('\n')}
}
`)
  console.log(`Wrote ${file} (${Date.now() - t0}ms)`)
}

main()
